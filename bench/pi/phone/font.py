W, H = 5, 7


def text_bits(s: str):
    """(rows of 0/1, width, height) for `s`, one blank column between glyphs."""
    rows = [[] for _ in range(H)]
    for i, ch in enumerate(s):
        g = GLYPHS.get(ch, GLYPHS[" "])
        for y in range(H):
            if i:
                rows[y].append(0)
            rows[y] += [int(c) for c in g[y]]
    return rows, len(rows[0]), H


def js() -> str:
    import json
    return "const FONT = %s;\n" % json.dumps({k: v for k, v in GLYPHS.items()})
